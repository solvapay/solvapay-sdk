import { describe, expect, it } from 'vitest'
import { formatCoreSurfaceChangeset, latestUnifiedTag } from './core-surface-changeset.js'

describe('core-surface changeset emit', () => {
  it('writes a sentinel changeset with a derived summary', () => {
    const body = formatCoreSurfaceChangeset('minor', [
      { bump: 'minor', summary: 'added `operations.listRefunds` (POST /v1/sdk/refunds)' },
      { bump: 'minor', summary: 'added optional argument `cursor` to `listPurchases`' },
    ])
    expect(body).toBe(
      [
        '---',
        "'@solvapay/release-train': minor",
        '---',
        '',
        '<!-- @generated by pnpm gen — do not edit -->',
        '',
        'Core surface: added `operations.listRefunds` (POST /v1/sdk/refunds), added optional argument `cursor` to `listPurchases`.',
        '',
        '- added `operations.listRefunds` (POST /v1/sdk/refunds)',
        '- added optional argument `cursor` to `listPurchases`',
        '',
      ].join('\n'),
    )
  })

  it('writes nothing as a baseline when no unified tag exists', () => {
    expect(latestUnifiedTag('/tmp', () => '')).toBeNull()
    expect(latestUnifiedTag('/tmp', () => 'solvapay-python-v0.1.0\n')).toBeNull()
    expect(latestUnifiedTag('/tmp', () => 'v3.0.0\nv2.0.0\n')).toBe('v3.0.0')
  })
})
