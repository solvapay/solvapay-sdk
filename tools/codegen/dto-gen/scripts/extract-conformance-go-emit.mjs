#!/usr/bin/env node
// Extracts Go fixture-conformance chrome from sdks/go/internal/contract/
// into assets/conformance-go-emit.snapshot.json.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, '..', '..', '..', '..');
const CONTRACT = join(REPO_ROOT, 'sdks', 'go', 'internal', 'contract');
const OUT_PATH = join(
  REPO_ROOT,
  'tools',
  'codegen',
  'dto-gen',
  'assets',
  'conformance-go-emit.snapshot.json',
);

const FILE_ORDER = [
  'clock.go',
  'names.go',
  'fixture_loader.go',
  'compare.go',
  'stub_backend.go',
  'host_adapters.go',
  'dispatch.go',
];

const HEADER =
  '// @generated by dto-gen — do not edit. Regenerate with --go-conformance-out.\n\n';

const NOW_MS_BLOCK =
  /(?:\tif fn == "[^"]+" \{\n\t\tclock := fixture\.Input\.Clock\n\t\tif clock == "" \{\n\t\t\treturn Outcome\{\}, fmt\.Errorf\("input\.clock is required for [^"]+"\)\n\t\t\}\n\t\tms, err := UnixMs\(clock\)\n\t\tif err != nil \{\n\t\t\treturn Outcome\{\}, err\n\t\t\}\n\t\targs\["nowMs"\] = ms\n\t\}\n)+/;

const HOST_FNS_INNER =
  /var HostFns = map\[string\]struct\{\}\{\n((?:\t"[^"]+":\s+\{\},\n)+)\}/;

function stripGeneratedHeader(src) {
  if (!src.startsWith('// @generated')) {
    return src;
  }
  const nl = src.indexOf('\n');
  let rest = nl === -1 ? '' : src.slice(nl + 1);
  if (rest.startsWith('\n')) {
    rest = rest.slice(1);
  }
  return rest;
}

function extractQuoted(inner) {
  return [...inner.matchAll(/"([^"]+)"/g)].map(match => match[1]);
}

const onDisk = new Set(
  readdirSync(CONTRACT).filter(name => name.endsWith('.go') && !name.startsWith('.')),
);
for (const name of FILE_ORDER) {
  if (!onDisk.has(name)) {
    throw new Error(`missing contract module ${name}`);
  }
}
for (const name of onDisk) {
  if (!FILE_ORDER.includes(name)) {
    throw new Error(`unexpected contract module ${name} — add it to FILE_ORDER or exclude it`);
  }
}

const files = {};
let hostFns;
let dispatchSpecialCases;

for (const name of FILE_ORDER) {
  let body = stripGeneratedHeader(readFileSync(join(CONTRACT, name), 'utf8'));
  if (name === 'host_adapters.go') {
    const hostMatch = body.match(HOST_FNS_INNER);
    if (!hostMatch) {
      throw new Error('host_adapters.go missing HostFns map');
    }
    hostFns = extractQuoted(hostMatch[1]);
    body = body.replace(hostMatch[0], 'var HostFns = map[string]struct{}{\n{{HOST_FNS}}\n}');
  }
  if (name === 'dispatch.go') {
    const assertMatch = body.match(
      /if fn == "([^"]+)" \{\n\t\t\treturn Outcome\{OK: false, ErrorName: "Error"/,
    );
    if (!assertMatch) {
      throw new Error('dispatch.go missing assertResponseResult special case');
    }
    const validateMatch = body.match(/if fn == "([^"]+)" \{\n\t\tif s, ok := value\.\(string\)/);
    if (!validateMatch) {
      throw new Error('dispatch.go missing validatePublicBaseUrl special case');
    }
    dispatchSpecialCases = {
      [assertMatch[1]]: 'js_error',
      [validateMatch[1]]: 'option_string_as_error',
    };
    if (!NOW_MS_BLOCK.test(body)) {
      throw new Error('dispatch.go missing nowMs clock-injection block');
    }
    body = body.replace(NOW_MS_BLOCK, '{{NOW_MS_INJECTION}}');
    if (/var SyncExports = map\[string\]string\{\}/.test(body)) {
      body = body.replace(
        'var SyncExports = map[string]string{}',
        'var SyncExports = map[string]string{\n{{SYNC_EXPORTS}}\n}',
      );
    } else {
      const syncMatch = body.match(
        /var SyncExports = map\[string\]string\{\n((?:\t"[^"]+":\s+"[^"]+",\n)*)\}/,
      );
      if (!syncMatch) {
        throw new Error('dispatch.go missing SyncExports map');
      }
      body = body.replace(syncMatch[0], 'var SyncExports = map[string]string{\n{{SYNC_EXPORTS}}\n}');
    }
  }
  files[name] = { body };
}

const snapshot = {
  header: HEADER,
  files,
  hostFns,
  dispatchSpecialCases,
};

writeFileSync(OUT_PATH, `${JSON.stringify(snapshot, null, 2)}\n`);
console.log(
  `wrote ${OUT_PATH} files=${FILE_ORDER.length} hostFns=${hostFns.length}`,
);
