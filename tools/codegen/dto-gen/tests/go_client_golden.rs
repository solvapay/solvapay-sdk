//! Golden tests for generated Go facade client.

#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

mod support;

use std::fs;

use dto_gen::emit_client_go;

#[test]
fn go_client_matches_committed_and_has_36_ctx_first_methods() {
    let ir = support::lower_bindings_ir();
    let emitted = emit_client_go(&ir).expect("emit Go client");
    let committed = fs::read_to_string(
        support::paths()
            .generated_path("goClient")
            .expect("goClient"),
    )
    .expect("client_generated.go");
    assert_eq!(emitted, committed);

    assert_eq!(emitted.matches("func (c *Client) ").count(), 43);
    assert!(emitted.contains("// Code generated by dto-gen. DO NOT EDIT."));
    assert!(emitted.contains("// @generated"));
    assert!(emitted.contains("func (c *Client) GetMerchant(ctx context.Context) (any, error)"));
    assert!(emitted.contains(
        "func (c *Client) CreateCustomer(ctx context.Context, params map[string]any) (any, error)"
    ));
    assert!(emitted.contains(
        "func (c *Client) UpdateCustomer(ctx context.Context, customerRef string, params map[string]any) (any, error)"
    ));
    assert!(emitted.lines().any(|l| l.starts_with("// GetMerchant ")));
    assert!(emitted.lines().any(|l| l.starts_with("// CheckLimits ")));
}
