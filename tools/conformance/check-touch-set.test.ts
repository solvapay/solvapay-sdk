import { describe, expect, it } from 'vitest'
import { checkTouchSet } from './check-touch-set.js'

const valid = {
  indexSrc: "export * from './barrel.generated'\n",
  barrelSrc: "export * from './native-helpers'\n",
  syncDispatchSrc: 'include!("sync_dispatch.generated.rs");\n',
  syncDispatchGeneratedSrc: '// @generated by dto-gen\n',
}

describe('touch-set gate', () => {
  it('requires the TS barrel re-export', () => {
    expect(
      checkTouchSet({
        ...valid,
        indexSrc: "export { foo } from './native-helpers'\n",
      }),
    ).toMatch(/barrel.generated/)
  })

  it('rejects helper bodies in the generated barrel', () => {
    expect(
      checkTouchSet({
        ...valid,
        barrelSrc: "export * from './native-helpers'\nexport function extra() { return 1 }\n",
      }),
    ).toMatch(/re-export barrel/)
  })

  it('requires the barrel to re-export native-helpers', () => {
    expect(
      checkTouchSet({
        ...valid,
        barrelSrc: 'export {}\n',
      }),
    ).toMatch(/native-helpers/)
  })

  it('requires generated MCP sync dispatch', () => {
    expect(
      checkTouchSet({
        ...valid,
        syncDispatchSrc: 'match op { "foo" => {} }\n',
        syncDispatchGeneratedSrc: 'fn dispatch() {}\n',
      }),
    ).toMatch(/generated/)
  })

  it('accepts the generated touch set', () => {
    expect(checkTouchSet(valid)).toBeUndefined()
  })
})
