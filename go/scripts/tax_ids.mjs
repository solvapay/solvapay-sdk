// Writes ../business_details_taxids_gen.go: the tax-ID tables @solvapay/core
// validates business details with (packages/core/src/tax-jurisdictions.ts), so
// Go accepts and rejects exactly what TypeScript does.
//
// Run from go/ with Node 24 (it loads the TypeScript source directly):
//   node scripts/tax_ids.mjs           # write
//   node scripts/tax_ids.mjs --check   # fail if the committed file is stale (CI)
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  COUNTRY_TO_TAX_ID_TYPE,
  EU_MEMBER_COUNTRIES,
  EU_VAT_FORMAT_BY_COUNTRY,
  SUPPORTED_BUSINESS_COUNTRIES,
  TAX_ID_FORMAT_BY_TYPE,
  TAX_ID_TYPES,
} from '../../packages/core/src/tax-jurisdictions.ts'

// A JavaScript pattern means the same in Go's RE2 only without flags,
// lookaround or backreferences; `\d` and `\s` are ASCII in RE2, so a pattern
// using `\s` (Unicode in JavaScript) is refused too.
function pattern(where, regex) {
  if (regex.flags !== '' || /\(\?[=!<]|\\[1-9]|\\s/.test(regex.source)) {
    throw new Error(`${where}: /${regex.source}/${regex.flags} has no Go RE2 equivalent`)
  }
  return `regexp.MustCompile(${JSON.stringify(regex.source)})`
}

const quoted = values => values.map(value => `\t${JSON.stringify(value)}: true,`)
const lines = [
  '// Code generated by go/scripts/tax_ids.mjs from packages/core/src/tax-jurisdictions.ts. DO NOT EDIT.',
  '',
  'package solvapay',
  '',
  'import "regexp"',
  '',
  '// buyerCountries are the countries Stripe Tax calculates tax for, as a buyer\'s country.',
  'var buyerCountries = map[string]bool{',
  ...quoted(SUPPORTED_BUSINESS_COUNTRIES),
  '}',
  '',
  'var euMemberCountries = map[string]bool{',
  ...quoted(EU_MEMBER_COUNTRIES),
  '}',
  '',
  '// TaxIDTypes are the tax-ID types Stripe accepts, in the TypeScript order.',
  'var TaxIDTypes = []string{',
  ...TAX_ID_TYPES.map(type => `\t${JSON.stringify(type)},`),
  '}',
  '',
  'var countryToTaxIDType = map[string]string{',
  ...Object.entries(COUNTRY_TO_TAX_ID_TYPE).map(
    ([country, type]) => `\t${JSON.stringify(country)}: ${JSON.stringify(type)},`,
  ),
  '}',
  '',
  'var taxIDFormatByType = map[string]*regexp.Regexp{',
  ...Object.entries(TAX_ID_FORMAT_BY_TYPE).map(
    ([type, regex]) => `\t${JSON.stringify(type)}: ${pattern(type, regex)},`,
  ),
  '}',
  '',
  'var euVATFormatByCountry = map[string]*regexp.Regexp{',
  ...Object.entries(EU_VAT_FORMAT_BY_COUNTRY).map(
    ([country, regex]) => `\t${JSON.stringify(country)}: ${pattern(country, regex)},`,
  ),
  '}',
  '',
]

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'business_details_taxids_gen.go')
// gofmt aligns the map values; the committed file is its output.
const text = execFileSync('gofmt', { input: lines.join('\n'), encoding: 'utf-8' })
if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(out, 'utf-8')
  } catch {
    // Missing counts as stale.
  }
  if (current !== text) {
    console.error('go/business_details_taxids_gen.go is out of date. Run: node go/scripts/tax_ids.mjs')
    process.exit(1)
  }
  console.log('The tax-ID tables are up to date')
} else {
  writeFileSync(out, text)
  console.log(`Wrote ${out}`)
}
