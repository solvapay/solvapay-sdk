// Writes ../narrate_currencies_gen.go: what Intl.NumberFormat('en-US', { style:
// 'currency' }) puts before an amount in each currency ("$", "CA$", "SEK "),
// and the fraction digits ICU shows by default where that is not 2, so Go
// formats money byte for byte as the TypeScript SDK does. Every currency ICU
// knows formats as a prefix; this script fails if that ever stops being true.
//
// Run from go/ with Node:  go generate ./...   (or node scripts/currencies.mjs [--check])
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const prefixes = []
const digits = []
for (const code of Intl.supportedValuesOf('currency')) {
  const format = new Intl.NumberFormat('en-US', {
    style: 'currency',
    currency: code,
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  })
  const text = format.format(1234.5)
  const at = text.indexOf('1,234.50')
  if (at < 0 || at + '1,234.50'.length !== text.length) {
    throw new Error(`${code} does not format as prefix + amount: ${JSON.stringify(text)}`)
  }
  prefixes.push(`\t${JSON.stringify(code)}: ${JSON.stringify(text.slice(0, at))},`)
  const { minimumFractionDigits } = new Intl.NumberFormat('en-US', {
    style: 'currency',
    currency: code,
  }).resolvedOptions()
  if (minimumFractionDigits !== 2) digits.push(`\t${JSON.stringify(code)}: ${minimumFractionDigits},`)
}

const source = [
  `// Code generated by go/scripts/currencies.mjs from Node ${process.version} (ICU ${process.versions.icu}). DO NOT EDIT.`,
  '',
  'package solvapay',
  '',
  "// intlCurrencyPrefix is what Intl.NumberFormat('en-US', { style: 'currency' }) puts before an amount.",
  'var intlCurrencyPrefix = map[string]string{',
  ...prefixes,
  '}',
  '',
  '// intlCurrencyDigits is the fraction digits ICU shows by default, where that is not 2.',
  'var intlCurrencyDigits = map[string]int{',
  ...digits,
  '}',
  '',
].join('\n')
const text = execFileSync('gofmt', { input: source, encoding: 'utf-8' })

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'narrate_currencies_gen.go')
if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(out, 'utf-8')
  } catch {
    // Missing counts as stale.
  }
  if (current !== text) {
    console.error('go/narrate_currencies_gen.go is out of date. Run: node go/scripts/currencies.mjs')
    process.exit(1)
  }
  console.log('The currency table is up to date')
} else {
  writeFileSync(out, text)
  console.log(`Wrote ${prefixes.length} currency prefixes`)
}
