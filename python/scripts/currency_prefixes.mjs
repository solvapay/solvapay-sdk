// Writes src/solvapay/_currencies.py: the prefix Intl.NumberFormat('en-US') puts
// before an amount in each currency ("$", "CA$", "SEK "), so Python formats
// money byte for byte as the TypeScript SDK does. Every currency ICU knows
// formats as a prefix; this script fails if that ever stops being true.
//
// Run with Node:  node python/scripts/currency_prefixes.mjs
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const prefixes = {}
for (const code of Intl.supportedValuesOf('currency')) {
  const text = new Intl.NumberFormat('en-US', {
    style: 'currency',
    currency: code,
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  }).format(1234.5)
  const at = text.indexOf('1,234.50')
  if (at < 0 || at + '1,234.50'.length !== text.length) {
    throw new Error(`${code} does not format as prefix + amount: ${JSON.stringify(text)}`)
  }
  prefixes[code] = text.slice(0, at)
}

const lines = [
  '"""GENERATED by python/scripts/currency_prefixes.mjs from Node',
  `${process.version} (ICU ${process.versions.icu}). Do not edit.`,
  '',
  "What Intl.NumberFormat('en-US', { style: 'currency' }) puts before an amount.",
  '"""',
  '',
  'PREFIXES: dict[str, str] = {',
  ...Object.entries(prefixes).map(
    ([code, prefix]) => `    ${JSON.stringify(code)}: ${JSON.stringify(prefix)},`,
  ),
  '}',
  '',
]
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'solvapay', '_currencies.py')
writeFileSync(out, lines.join('\n'))
console.log(`Wrote ${Object.keys(prefixes).length} currency prefixes`)
