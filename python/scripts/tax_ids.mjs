// Writes src/solvapay/_tax_ids.py: the tax-ID tables @solvapay/core validates
// business details with (packages/core/src/tax-jurisdictions.ts), so the
// Python `attach_business_details` tool accepts and rejects exactly what the
// TypeScript one does.
//
// Run with Node 24 (it loads the TypeScript source directly):
//   node python/scripts/tax_ids.mjs           # write
//   node python/scripts/tax_ids.mjs --check   # fail if the committed file is stale (CI)
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  COUNTRY_TO_TAX_ID_TYPE,
  EU_MEMBER_COUNTRIES,
  EU_VAT_FORMAT_BY_COUNTRY,
  SUPPORTED_BUSINESS_COUNTRIES,
  TAX_ID_FORMAT_BY_TYPE,
  TAX_ID_TYPES,
} from '../../packages/core/src/tax-jurisdictions.ts'

// A JavaScript pattern means the same in Python only without flags or named
// groups; `\d` is ASCII in JavaScript, so Python compiles with re.ASCII.
function pattern(where, regex) {
  if (regex.flags !== '' || regex.source.includes('(?<')) {
    throw new Error(`${where}: /${regex.source}/${regex.flags} has no Python equivalent`)
  }
  return JSON.stringify(regex.source)
}

const list = values => values.map(value => `    ${JSON.stringify(value)},`)
const lines = [
  '"""GENERATED by python/scripts/tax_ids.mjs from packages/core/src/tax-jurisdictions.ts.',
  'Do not edit."""',
  '',
  'import re',
  '',
  'BUYER_COUNTRIES: frozenset[str] = frozenset(',
  '    (',
  ...list(SUPPORTED_BUSINESS_COUNTRIES).map(line => `    ${line}`),
  '    )',
  ')',
  '',
  'EU_MEMBER_COUNTRIES: frozenset[str] = frozenset(',
  '    (',
  ...list(EU_MEMBER_COUNTRIES).map(line => `    ${line}`),
  '    )',
  ')',
  '',
  'TAX_ID_TYPES: tuple[str, ...] = (',
  ...list(TAX_ID_TYPES),
  ')',
  '',
  'COUNTRY_TO_TAX_ID_TYPE: dict[str, str] = {',
  ...Object.entries(COUNTRY_TO_TAX_ID_TYPE).map(
    ([country, type]) => `    ${JSON.stringify(country)}: ${JSON.stringify(type)},`,
  ),
  '}',
  '',
  'TAX_ID_FORMAT_BY_TYPE: dict[str, re.Pattern[str]] = {',
  ...Object.entries(TAX_ID_FORMAT_BY_TYPE).map(
    ([type, regex]) =>
      `    ${JSON.stringify(type)}: re.compile(${pattern(type, regex)}, re.ASCII),`,
  ),
  '}',
  '',
  'EU_VAT_FORMAT_BY_COUNTRY: dict[str, re.Pattern[str]] = {',
  ...Object.entries(EU_VAT_FORMAT_BY_COUNTRY).map(
    ([country, regex]) =>
      `    ${JSON.stringify(country)}: re.compile(${pattern(country, regex)}, re.ASCII),`,
  ),
  '}',
  '',
]

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'solvapay', '_tax_ids.py')
const text = lines.join('\n')
if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(out, 'utf-8')
  } catch {
    // Missing counts as stale.
  }
  if (current !== text) {
    console.error(
      'python/src/solvapay/_tax_ids.py is out of date. Run: node python/scripts/tax_ids.mjs',
    )
    process.exit(1)
  }
  console.log('The tax-ID tables are up to date')
} else {
  writeFileSync(out, text)
  console.log(`Wrote ${out}`)
}
