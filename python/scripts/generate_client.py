"""Generates the Python HTTP client from the committed SDK spec.

Reads ../openapi/sdk-v1.json and writes src/solvapay/_generated/:

- models.py: pydantic v2 models for every schema (datamodel-code-generator).
- operations.py: one async and one sync method per operation.

Run from python/:  uv run python scripts/generate_client.py
Add --check to fail instead of writing when the output would change (CI).

Inline response schemas are lifted into named components first, so every
response has a model. Nothing here is hand-edited after generation.
"""

from __future__ import annotations

import json
import keyword
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT.parent / "openapi" / "sdk-v1.json"
OUT = ROOT / "src" / "solvapay" / "_generated"

# Controller method names that are too vague for a public client.
RENAMES = {
    "activate": "activate_plan",
    "authorize": "authorize_agent_call",
    "complete": "complete_agent_call",
    "verify": "verify_agent_key",
    "report": "report_agent_usage",
    "getActivity": "get_credit_activity",
    "recordEvent": "record_meter_event",
    "recordBulkEvents": "record_meter_events_bulk",
    "recordBulkUsage": "record_usage_bulk",
    "getEventSchema": "get_webhook_event_schema",
    "listEventTypes": "list_webhook_event_types",
    "deleteAutoRecharge": "disable_auto_recharge",
    "putAutoRecharge": "save_auto_recharge",
}

HEADER = (
    '"""GENERATED by python/scripts/generate_client.py from openapi/sdk-v1.json. Do not edit."""\n'
)


def snake(name: str) -> str:
    out = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name).replace("-", "_").lower()
    return f"{out}_" if keyword.iskeyword(out) else out


def pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[_\-]", name) if part)


def method_name(operation_id: str) -> str:
    short = re.sub(r"^[A-Za-z]+Controller_", "", operation_id)
    return RENAMES.get(short, snake(short))


def lift_inline_schemas(spec: dict[str, Any]) -> dict[str, Any]:
    """Moves inline 2xx response schemas into components, named <Method>Response."""
    schemas = spec["components"]["schemas"]
    for item in spec["paths"].values():
        for operation in item.values():
            for status, response in operation.get("responses", {}).items():
                media = response.get("content", {}).get("application/json")
                if not status.startswith("2") or not media or "$ref" in media.get("schema", {}):
                    continue
                name = pascal(method_name(operation["operationId"])) + "Response"
                if name in schemas:
                    raise SystemExit(f"Lifted schema name {name} collides with a spec schema")
                schemas[name] = media["schema"]
                media["schema"] = {"$ref": f"#/components/schemas/{name}"}
    return spec


# Formats the server validates. Kept as plain strings here, as the TypeScript
# SDK types them: the client must not reject data the API sent, nor need
# extra packages (email-validator) to read it.
STRING_FORMATS = {"email", "uri", "url", "date", "date-time"}


def strip_string_formats(node: Any) -> Any:
    if isinstance(node, list):
        return [strip_string_formats(item) for item in node]
    if not isinstance(node, dict):
        return node
    return {
        key: strip_string_formats(value)
        for key, value in node.items()
        if not (key == "format" and value in STRING_FORMATS and node.get("type") == "string")
    }


def ref_name(schema: dict[str, Any] | None) -> str | None:
    if not schema:
        return None
    ref = schema.get("$ref")
    return ref.rsplit("/", 1)[-1] if isinstance(ref, str) else None


def model_class(name: str, models_source: str) -> str:
    """The class datamodel-code-generator wrote for a schema name."""
    if re.search(rf"^class {re.escape(name)}\b", models_source, re.M):
        return name
    raise SystemExit(f"No model class {name} in models.py")


def build_operations(spec: dict[str, Any], models_source: str) -> str:
    methods: list[dict[str, Any]] = []
    for path, item in sorted(spec["paths"].items()):
        for http_method, operation in sorted(item.items()):
            params = operation.get("parameters", [])
            body_ref = ref_name(
                operation.get("requestBody", {})
                .get("content", {})
                .get("application/json", {})
                .get("schema")
            )
            success = [
                (
                    status,
                    ref_name(resp.get("content", {}).get("application/json", {}).get("schema")),
                )
                for status, resp in operation["responses"].items()
                if status.startswith("2")
            ]
            if len(success) != 1:
                raise SystemExit(f"{operation['operationId']} has {len(success)} success responses")
            methods.append(
                {
                    "name": method_name(operation["operationId"]),
                    "http": http_method.upper(),
                    "path": path,
                    "summary": (operation.get("summary") or "").strip(),
                    "path_params": [p for p in params if p["in"] == "path"],
                    "query_params": [p for p in params if p["in"] == "query"],
                    "header_params": [p for p in params if p["in"] == "header"],
                    "body": model_class(body_ref, models_source) if body_ref else None,
                    "body_required": operation.get("requestBody", {}).get("required", False),
                    "response": model_class(success[0][1], models_source)
                    if success[0][1]
                    else None,
                }
            )

    names = [m["name"] for m in methods]
    duplicates = {n for n in names if names.count(n) > 1}
    if duplicates:
        raise SystemExit(f"Duplicate method names: {sorted(duplicates)}")

    lines = [
        HEADER,
        "from __future__ import annotations\n",
        "from typing import Any\n",
        "from .._http import AsyncTransport, SyncTransport, encode_body, path_segment",
        "from . import models\n\n",
    ]
    for cls, transport, aw in (
        ("AsyncSolvaPayApi", "AsyncTransport", "await "),
        ("SolvaPayApi", "SyncTransport", ""),
    ):
        kind = "async" if aw else "blocking"
        lines.append(f"class {cls}:")
        lines.append(f'    """Every SolvaPay API operation, {kind}: one method per operation."""\n')
        lines.append(f"    def __init__(self, transport: {transport}) -> None:")
        lines.append("        self._transport = transport\n")
        for m in methods:
            lines.extend(render_method(m, aw))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def py_type(schema: dict[str, Any]) -> str:
    kind = schema.get("type")
    return {"integer": "int", "number": "float", "boolean": "bool"}.get(kind, "str")


def render_method(m: dict[str, Any], aw: str) -> list[str]:
    args: list[str] = ["self"]
    required: list[str] = []
    optional: list[str] = []
    for p in m["path_params"]:
        required.append(f"{snake(p['name'])}: str")
    if m["body"]:
        hint = f"models.{m['body']} | dict[str, Any]"
        (required if m["body_required"] else optional).append(
            f"body: {hint}" if m["body_required"] else f"body: {hint} | None = None"
        )
    for p in m["query_params"] + m["header_params"]:
        t = py_type(p.get("schema", {}))
        if p.get("required"):
            required.append(f"{snake(p['name'])}: {t}")
        else:
            optional.append(f"{snake(p['name'])}: {t} | None = None")
    if required or optional:
        args.append("*")
    args.extend(required + optional)

    path_expr = m["path"]
    for p in m["path_params"]:
        path_expr = path_expr.replace(
            "{" + p["name"] + "}", "{path_segment(" + snake(p["name"]) + ")}"
        )
    returns = f"models.{m['response']}" if m["response"] else "None"
    prefix = "async def" if aw else "def"

    out = [f"    {prefix} {m['name']}(", *[f"        {a}," for a in args], f"    ) -> {returns}:"]
    doc = f"{m['http']} {m['path']}"
    if m["summary"]:
        doc = f"{m['summary']}\n\n        {doc}"
    out.append(f'        """{doc}"""')
    query = ", ".join(f'"{p["name"]}": {snake(p["name"])}' for p in m["query_params"])
    headers = ", ".join(f'"{p["name"]}": {snake(p["name"])}' for p in m["header_params"])
    call = (
        f"        data = {aw}self._transport.request(\n"
        f'            "{m["http"]}",\n'
        f'            f"{path_expr}",\n'
        f"            query={{{query}}},\n"
        f"            headers={{{headers}}},\n"
        f"            body={'encode_body(body)' if m['body'] else 'None'},\n"
        f"        )"
    )
    out.append(call)
    if m["response"]:
        out.append(f"        return self._transport.parse(models.{m['response']}, data)")
    else:
        out.append("        return None")
    out.append("")
    return out


def ruff_format(source: str, filename: str) -> str:
    result = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", filename, "-"],
        input=source,
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        raise SystemExit(f"ruff format failed on {filename}:\n{result.stderr}")
    return result.stdout


def generate_models(spec_path: Path) -> str:
    result = subprocess.run(
        [
            sys.executable,
            "-m",
            "datamodel_code_generator",
            "--input",
            str(spec_path),
            "--input-file-type",
            "openapi",
            "--output-model-type",
            "pydantic_v2.BaseModel",
            "--target-python-version",
            "3.10",
            "--use-annotated",
            "--field-constraints",
            "--strict-nullable",
            "--use-union-operator",
            "--use-standard-collections",
            "--snake-case-field",
            "--use-double-quotes",
            "--disable-timestamp",
            "--enum-field-as-literal",
            "all",
            "--use-schema-description",
            "--use-field-description",
            "--extra-fields",
            "allow",
            "--allow-population-by-field-name",
            "--formatters",
            "ruff-format",
            "--custom-file-header",
            HEADER.strip(),
        ],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        raise SystemExit(f"datamodel-code-generator failed:\n{result.stderr}")
    # JSON has one number type. Typed `float`, pydantic turns 2 into 2.0 and the
    # SDK sends 2.0 where TypeScript sends 2. `int | float` keeps each as sent.
    return re.sub(r"\bfloat\b", "int | float", result.stdout)


def main() -> None:
    check = "--check" in sys.argv
    spec = lift_inline_schemas(strip_string_formats(json.loads(SPEC.read_text())))
    with tempfile.TemporaryDirectory() as tmp:
        spec_path = Path(tmp) / "sdk-v1.json"
        spec_path.write_text(json.dumps(spec))
        models_source = generate_models(spec_path)
    operations_source = ruff_format(build_operations(spec, models_source), "operations.py")
    outputs = {
        OUT / "__init__.py": HEADER,
        OUT / "models.py": models_source,
        OUT / "operations.py": operations_source,
    }
    if check:
        stale = [p.name for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        if stale:
            raise SystemExit(
                f"The generated client is out of date ({', '.join(stale)}). "
                "Run: uv run python scripts/generate_client.py"
            )
        print("The generated client is up to date")
        return
    OUT.mkdir(parents=True, exist_ok=True)
    for path, text in outputs.items():
        path.write_text(text)
    print(f"Wrote {', '.join(p.name for p in outputs)}")


if __name__ == "__main__":
    main()
